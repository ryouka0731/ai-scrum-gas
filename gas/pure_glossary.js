/** 用語の説明を返す。知らない語なら空文字。 */
function glossaryOf(term) {
  const key = String(term === null || term === undefined ? '' : term).trim();
  if (!key) return '';
  return Object.prototype.hasOwnProperty.call(GLOSSARY, key) ? GLOSSARY[key] : '';
}

